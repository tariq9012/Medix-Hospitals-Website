function makeDoctor(
  i: number,
  name: string,
  specialty: string,
  gender: "male" | "female",
  city: string,
  hospitalIndex: number,
  fee: number,
  experience: number,
  rating: number,
): Doctor {
  return {
    id: `doc-${i + 1}`,
    name,
    specialty,
    qualification:
      specialty === "Dentistry"
        ? "BDS, FCPS (Operative Dentistry)"
        : "MBBS, FCPS (" + specialty + ")",
    experience,
    rating,
    reviews: 40 + ((i * 37) % 260),
    fee,
    gender,
    city,
    hospitalId: `hos-${hospitalIndex + 1}`,
    hospital: hospitals[hospitalIndex]!.name,
    online: i % 3 !== 2,
    inPerson: true,
    verified: i % 7 !== 5,
    image: portraits[i % portraits.length]!,
    languages: ["English", "Urdu", i % 2 ? "Punjabi" : "Pashto"],
    about: `${name} is a ${specialty.toLowerCase()} consultant with ${experience} years of clinical practice. Focused on evidence-based care, ${name.split(" ")[1]} treats both routine and complex cases and is known for clear explanations and unhurried consultations.`,
    nextAvailable: ["Today, 4:30 PM", "Tomorrow, 10:00 AM", "Mon, 2:00 PM"][i % 3]!,
    services: [
      {
        name: "General Consultation",
        description: "Assessment, diagnosis and treatment plan",
        price: fee,
      },
      {
        name: "Follow-up Visit",
        description: "Progress review within 14 days",
        price: Math.round(fee * 0.6),
      },
      {
        name: "Online Consultation",
        description: "Secure video consultation",
        price: Math.round(fee * 0.8),
      },
    ],
    education: [
      { degree: "MBBS", institute: "King Edward Medical University", year: `${2000 + (i % 6)}` },
      {
        degree: `FCPS ${specialty}`,
        institute: "College of Physicians & Surgeons",
        year: `${2008 + (i % 5)}`,
      },
      { degree: "Fellowship", institute: "Royal College, UK", year: `${2013 + (i % 4)}` },
    ],
    timeline: [
      {
        role: `Consultant ${specialty}`,
        place: hospitals[hospitalIndex]!.name,
        period: `${2018 - (i % 4)} — Present`,
        detail: "Leads outpatient clinics and supervises resident training.",
      },
      {
        role: "Senior Registrar",
        place: "National Medical Centre",
        period: `${2013 - (i % 3)} — ${2018 - (i % 4)}`,
        detail: "Managed inpatient wards and emergency admissions.",
      },
      {
        role: "Medical Officer",
        place: "City General Hospital",
        period: `${2010 - (i % 2)} — ${2013 - (i % 3)}`,
        detail: "Rotations across medicine, surgery and emergency care.",
      },
    ],
  };
}

